B = np.array(([Bx,By,Bz]))
#-------------------------------------------------------------------------------

#Hamiltonian
H = x_A_x_mult(S,D,S) + gamma*Sz*B[2]

#Time evolution with the hamiltonian
def timestep(Psi, N,dt):
  Psis = []
  for i in range(N):
    Psi = Psi - (1j/hbar)*H@Psi*dt
    Psis.append(Psi)
  return np.array(Psis)

