#calculating the energies for changing B field strength in z direction
#Modes:
#no_nucl:   just ZFS and Zeeman terms
#full:      all the terms
#full_mult: all the terms for multiple I_k
def calc_energies(S, D, Bs, I=None, A=None, gamma_k=[None], Q=None, mode="no_nucl"):
  E1 = []
  E2 = []
  E3 = []
  for B0 in Bs:
    B = np.array(([0,0,-B0]))
    if(mode=="no_nucl"):
      H = x_A_x_mult(S,D,S) + gamma*S[2]*B0
    elif(mode=="full"):
      #needs some attention
      H = x_A_x_mult(S,D,S) + gamma*S[2]*B0 + x_A_x_mult(S,A,I) - gamma_k[0]*B0*I[2] - x_A_x_mult(I,Q,I)
    #H = dxx*Sx*Sx + dyy*Sy*Sy + dzz*Sz*Sz + gamma*Sz*B0
    E = np.linalg.eig(H)
    E1.append(np.real_if_close(E[0][0]))
    E2.append(np.real_if_close(E[0][1]))
    E3.append(np.real_if_close(E[0][2]))
  return E1, E2, E3

