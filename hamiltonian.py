#defining the S tensors
#for S=1, the three eigenstates are |1,1>, |1,0> and |1,-1> which correspont to the vectors (1,0,0), (0,1,0) and (0,0,1).
hbar = 1
Sx = (hbar/np.sqrt(2))*np.array(([0,1,0],[1,0,1],[0,1,0]))
Sy = (hbar/np.sqrt(2))*np.array(([0,-1j,0],[1j,0,-1j],[0,1j,0]))
Sz = (hbar/np.sqrt(2))*np.array(([1,0,0],[0,0,0],[0,0,-1]))
S = np.array(([Sx,Sy,Sz]))

#definition of (operator-vector, operator, operator-vector) double multiplication
def x_A_x_mult(A,B,C):
  if ((abs(B[0][1]) + abs(B[0][2]) + abs(B[1][0]) + abs(B[1][2]) + abs(B[2][0]) + abs(B[2][1]))<1e-5 ):
    return B[0][0]*S[0]*S[0] + B[1][1]*S[1]*S[1] + B[2][2]*S[2]*S[2]
  return A[0]*(B[0][0]*C[0] + B[0][1]*C[1] + B[0][2]*C[2]) + A[1]*(B[1][0]*C[0] + B[1][1]*C[1] + B[1][2]*C[2]) + A[2]*(B[2][0]*C[0] + B[2][1]*C[1] + B[2][2]*C[2])


#Momentary definitions----------------------------------------------------------
#definition of the ZFS tensor
dxx = 1
dyy = 1
dzz = -2
D = np.array(([dxx,0,0,],[0,dyy,0],[0,0,dzz]))
#definition of the magnetic field
Bx = 0
